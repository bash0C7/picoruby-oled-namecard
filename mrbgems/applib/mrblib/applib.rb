class Button
  HIGH = 1
  LOW = 0
  
  def initialize(pin)
    @gpio = GPIO.new(pin, GPIO::IN)
    @last_state = HIGH
    @pressed = false
    @on_press_callback = Proc.new {}
  end
  
  def on_press(&block)
    @on_press_callback = block
  end
  
  def update
    current = @gpio.read
    if @last_state == HIGH && current == LOW && !@pressed
      @pressed = true
      @on_press_callback.call
    elsif current == HIGH
      @pressed = false
    end
    @last_state = current
  end
end

